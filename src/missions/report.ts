/**
 * agentika-canvas: Mission report rendering (Markdown)
 */

import { MissionReport, MissionCheckResult } from './types';

function renderChecks(checks: MissionCheckResult[]): string {
  return checks
    .map((c) => {
      const mark = c.skipped ? '⏭' : c.passed ? '✅' : c.severity === 'warning' ? '⚠️' : '❌';
      const line = `- ${mark} **${c.label}** — ${c.details}`;
      return line;
    })
    .join('\n');
}

const STATUS_BADGE: Record<string, string> = {
  passed: '✅ **PASSED**',
  failed: '❌ **FAILED**',
  halted: '⛔ **HALTED** (kegagalan sama berulang)',
  running: '⏳ RUNNING',
  pending: '⏳ PENDING',
};

/** Render a full Markdown report for a mission run. */
export function renderMissionMarkdown(report: MissionReport): string {
  const lines: string[] = [];

  lines.push(`# Mission Report: ${report.sceneId}`);
  lines.push('');
  lines.push(`- Status: ${STATUS_BADGE[report.status] ?? report.status}`);
  lines.push(`- Started: ${report.startedAt}`);
  lines.push(`- Finished: ${report.finishedAt}`);
  lines.push(`- Attempts: ${report.totalAttempts} / max ${report.maxAttempts}`);
  if (report.failureSignature) {
    lines.push(`- Failure signature: \`${report.failureSignature}\``);
  }
  lines.push('');
  lines.push(`> ${report.summary}`);
  lines.push('');

  if (report.manualNotes.length) {
    lines.push('## Catatan Manual (FrameInspector)');
    lines.push('');
    for (const n of report.manualNotes) lines.push(`- ${n}`);
    lines.push('');
  }

  for (const attempt of report.attempts) {
    lines.push(`## Attempt ${attempt.index} — ${attempt.status === 'passed' ? '✅ passed' : '❌ failed'}`);
    lines.push('');
    lines.push(`Duration: ${attempt.durationMs} ms | Signature: \`${attempt.failureSignature || '-'}\``);
    lines.push('');
    lines.push('### Checks');
    lines.push('');
    lines.push(renderChecks(attempt.checks));
    lines.push('');
    lines.push('### Evidence (sampled frames)');
    lines.push('');
    lines.push('| frame | timestamp µs | draw calls | NaN calls | luma mean | luma var |');
    lines.push('|---:|---:|---:|---:|---:|---:|');
    for (const e of attempt.evidence) {
      const luma = e.pixelLuma
        ? `${e.pixelLuma.mean.toFixed(1)} | ${e.pixelLuma.variance.toFixed(1)}`
        : '— | —';
      lines.push(`| ${e.frame} | ${e.timestampUs} | ${e.drawCalls} | ${e.nanCalls} | ${luma} |`);
    }
    lines.push('');
    if (attempt.review && attempt.review.notes.length) {
      lines.push('### Reviewer');
      lines.push('');
      lines.push(`Verdict: \`${attempt.review.verdict}\``);
      lines.push('');
      for (const n of attempt.review.notes) lines.push(`- ${n}`);
      lines.push('');
    }
  }

  lines.push('---');
  lines.push('');
  lines.push('*Generated by agentika-canvas Mission Pipeline. Export gate: hanya scene ber-status `passed` yang boleh dirender ke MP4.*');
  lines.push('');
  return lines.join('\n');
}
